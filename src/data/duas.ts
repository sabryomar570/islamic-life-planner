export const DUA_COUNT = DUAS.length;

export function duasBySection(section: DuaSectionId | "all") {
  if (section === "all") return DUAS;
  return DUAS.filter((dua) => dua.section === section);
}

export function duaOfTheDay(date: Date = new Date()): Dua {
  const seed = date.getFullYear() * 372 + (date.getMonth() + 1) * 31 + date.getDate();
  return DUAS[seed % DUAS.length];
}

export function randomDua(excludeId?: string | null): Dua {
  const pool = excludeId ? DUAS.filter((dua) => dua.id !== excludeId) : DUAS;
  const list = pool.length > 0 ? pool : DUAS;
  return list[Math.floor(Math.random() * list.length)];
}

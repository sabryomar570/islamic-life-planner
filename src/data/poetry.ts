export const POEM_COUNT = POEMS.length;

export function getPoem(id: string) {
  return POEMS.find((poem) => poem.id === id);
}

export function poemsByTheme(theme: PoemTheme | "الكل") {
  if (theme === "الكل") return POEMS;
  return POEMS.filter((poem) => poem.theme === theme);
}

/** بيت اليوم — يتبدّل يوميًا بلا تكرار حتى تدور الدورة كاملة. */
export function poemOfTheDay(date: Date = new Date()) {
  const seed = date.getFullYear() * 372 + (date.getMonth() + 1) * 31 + date.getDate();
  return POEMS[seed % POEMS.length];
}

/** يختار بيتًا مختلفًا عن الذي أمامك، ويعيد الخلط عند انتهاء المجموعة. */
export function nextPoem(currentId: string | null, pool: Poem[] = POEMS) {
  const source = pool.length > 0 ? pool : POEMS;
  if (source.length === 1) return source[0];
  const index = source.findIndex((poem) => poem.id === currentId);
  return source[(index + 1 + Math.floor(Math.random() * (source.length - 1))) % source.length];
}

export function randomPoem(excludeId?: string | null, pool: Poem[] = POEMS) {
  const source = pool.filter((poem) => poem.id !== excludeId);
  const list = source.length > 0 ? source : pool;
  if (list.length === 0) return null;
  return list[Math.floor(Math.random() * list.length)];
}

/** ترتيب عشوائي جديد لقائمة الأبيات (زر «خلط»). */
export function shufflePoems(pool: Poem[] = POEMS) {
  const copy = [...pool];
  for (let index = copy.length - 1; index > 0; index -= 1) {
    const swap = Math.floor(Math.random() * (index + 1));
    [copy[index], copy[swap]] = [copy[swap], copy[index]];
  }
  return copy;
}
